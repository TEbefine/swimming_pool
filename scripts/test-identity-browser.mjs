// Optional production-browser check. See docs/ai/ID-01-review.md for invocation.
import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
const url = process.env.IDENTITY_URL || 'http://127.0.0.1:4173/?perf=1';
const output = process.env.IDENTITY_REVIEW_DIR || '/tmp/id01-review';
await mkdir(output, { recursive: true });
const browser = await chromium.launch({ headless: true, ...(process.env.CHROME_EXECUTABLE ? { executablePath: process.env.CHROME_EXECUTABLE } : {}) });
try {
  const context = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true, colorScheme: 'light', serviceWorkers: 'block' });
  const page = await context.newPage();
  const requests = [];
  const errors = [];
  const consoleMessages = [];
  page.on('console', message => consoleMessages.push(message.text()));
  page.on('request', request => requests.push(request.url() + (request.postData() || '')));
  page.on('pageerror', error => errors.push(error.message));
  const button = name => page.getByRole('button', { name, exact: true });
  const heading = name => page.getByRole('heading', { name, exact: true });
  const visible = async locator => { await locator.waitFor({ state: 'visible' }); };
  const keys = ['ArrowUp', 'ArrowDown', 'ArrowLeft', 'ArrowRight', 't', 'o', 'x'];
  const nextKeys = ['q', 'q', 'ArrowLeft', 'ArrowRight', 't', 'o', 'x'];
  const enter = async sequence => { for (const key of sequence) await page.keyboard.press(key); };
  const dbRead = () => page.evaluate(() => new Promise((resolve, reject) => {
    const r = indexedDB.open('lumen-bay-identity', 1);
    r.onerror = () => reject(new Error('read failed'));
    r.onsuccess = () => {
      const db = r.result, tx = db.transaction('identity', 'readonly'), store = tx.objectStore('identity');
      const v = store.get('vault'), s = store.get('local-preview-receipt');
      tx.oncomplete = () => { db.close(); resolve({ vault: v.result ?? null, receipt: s.result ?? null }); };
    };
  }));
  const expire = () => page.evaluate(() => new Promise(resolve => {
    const r = indexedDB.open('lumen-bay-identity', 1);
    r.onsuccess = () => { const db = r.result, tx = db.transaction('identity', 'readwrite'), store = tx.objectStore('identity');
      const read = store.get('local-preview-receipt');
      read.onsuccess = () => store.put({ ...read.result, verifiedAt: Date.now() - 49 * 60 * 60 * 1000 }, 'local-preview-receipt');
      tx.oncomplete = () => { db.close(); resolve(); };
    };
  }));
  await page.goto(url);
  await visible(button('Restore with your 12 words'));
  assert.equal((await dbRead()).vault, null);
  await page.screenshot({ path: `${output}/identity-welcome.png` });
  await button('I’m new — create an identity').click();
  await visible(heading('Write these down'));
  const words = await page.locator('.identity-words li').evaluateAll(items => items.map(item => item.childNodes[item.childNodes.length - 1].textContent));
  assert.equal(words.length, 12);
  assert.ok(await page.locator('.identity-screen').evaluate(el => el.scrollWidth <= el.clientWidth), 'backup screen must not overflow horizontally');
  assert.equal(await button('Check my backup').isDisabled(), true);
  await page.getByLabel('I wrote all 12 words on paper.').check();
  await button('Check my backup').click();
  const fields = page.locator('form input[type=password]');
  for (let i = 0; i < 3; i++) await fields.nth(i).fill('wrong');
  await button('My backup is ready').click();
  await visible(page.getByRole('alert'));
  for (let i = 0; i < 3; i++) {
    const label = await fields.nth(i).locator('..').innerText();
    const position = Number(label.match(/Word (\d+)/)[1]);
    await fields.nth(i).fill(words[position - 1]);
  }
  await button('My backup is ready').click();
  await visible(heading('Choose your secret code'));
  assert.equal(await page.locator('.identity-words').count(), 0);
  await page.keyboard.down('ArrowUp'); await page.keyboard.down('ArrowUp'); await page.keyboard.up('ArrowUp');
  assert.equal(await page.locator('.identity-dots .filled').count(), 1);
  await page.keyboard.press('Backspace');
  // Touch press and drag must count only once, with no arrow colour feedback.
  const pad = page.locator('.identity-shell .minimal-socket').first();
  const bounds = await pad.boundingBox();
  const before = await pad.locator('polygon').first().evaluate(el => getComputedStyle(el).fill);
  await page.mouse.move(bounds.x + bounds.width / 2, bounds.y + 10);
  await page.mouse.down(); await page.mouse.move(bounds.x + bounds.width - 10, bounds.y + bounds.height / 2);
  assert.equal(await pad.locator('polygon').first().evaluate(el => getComputedStyle(el).fill), before);
  await page.mouse.up();
  assert.equal(await page.locator('.identity-dots .filled').count(), 1);
  await page.keyboard.press('Backspace');
  const face = page.getByTitle('Cross (X)');
  const faceBefore = await face.evaluate(el => ({ transform: getComputedStyle(el).transform, shadow: getComputedStyle(el).boxShadow, color: getComputedStyle(el).color }));
  await face.hover(); await page.mouse.down();
  assert.deepEqual(await face.evaluate(el => ({ transform: getComputedStyle(el).transform, shadow: getComputedStyle(el).boxShadow, color: getComputedStyle(el).color })), faceBefore);
  await page.mouse.up(); await page.keyboard.press('Backspace');
  await enter(keys); await page.keyboard.press('q');
  assert.equal(await page.locator('.identity-dots .filled').count(), 7);
  await page.locator('.identity-screen').evaluate(el => el.scrollTo(0, 0));
  await page.screenshot({ path: `${output}/identity-code-light.png` });
  await page.emulateMedia({ colorScheme: 'dark' });
  await page.waitForFunction(() => getComputedStyle(document.querySelector('.identity-shell')).backgroundColor === 'rgb(22, 23, 27)');
  await page.screenshot({ path: `${output}/identity-code-dark.png` });
  await button('Use this code').click();
  await enter(nextKeys); await button('Confirm').click();
  await visible(heading('Choose your secret code'));
  await enter(keys); await button('Use this code').click();
  await enter(keys); await button('Confirm').click();
  await visible(heading('Ready for Lumen Bay'));
  const initial = await dbRead();
  assert.ok(!JSON.stringify(initial).includes(words.join(' ')), 'phrase must not be plaintext in IndexedDB');
  assert.equal(initial.vault.iterations, 600000);
  await page.reload();
  await page.locator('.identity-cover').waitFor({ state: 'detached' });
  await page.locator('.ls-ready').waitFor();
  await page.locator('.ls-ready').click();
  await page.locator('.ls-root').waitFor({ state: 'detached' });
  await page.getByTitle('Change Name', { exact: true }).click();
  await button('Player ID & recovery backup').click();
  await visible(heading('A place that’s yours'));
  await button('Continue to Lumen Bay').click();
  await page.locator('.identity-cover').waitFor({ state: 'detached' });
  assert.equal(await page.locator('.ls-root').count(), 0, 'settings must preserve the mounted game');
  console.log('PASS: mandatory backup, seven inputs, no press feedback, matching codes, encrypted storage, return within 48 hours.');
  await expire(); await page.reload(); await visible(heading('Welcome back'));
  await enter(nextKeys); await button('Confirm').click(); await visible(page.getByRole('alert'));
  await enter(keys); await button('Confirm').click(); await visible(heading('A place that’s yours'));
  const timing = await page.getByTestId('unlock-time').innerText();
  console.log(`Desktop browser measurement (NOT iPhone 13): ${timing}`);
  await button('Show my 12 words').click(); await visible(heading('One quick security check'));
  await enter(keys); await button('Confirm').click(); await visible(heading('Only for your eyes'));
  const recovered = await page.locator('.identity-words li').evaluateAll(items => items.map(item => item.childNodes[item.childNodes.length - 1].textContent));
  assert.ok(recovered.join(' ') === words.join(' '), 'decrypted backup must match');
  // Simulate the visibility lifecycle without asking a human to background the window.
  await page.evaluate(() => { Object.defineProperty(document, 'hidden', { value: true, configurable: true }); document.dispatchEvent(new Event('visibilitychange')); });
  await page.locator('.identity-words').waitFor({ state: 'detached' });
  await page.evaluate(() => { Object.defineProperty(document, 'hidden', { value: false, configurable: true }); document.dispatchEvent(new Event('visibilitychange')); });
  await visible(heading('A place that’s yours'));
  await button('Change my controller code').click();
  await enter(keys); await button('Confirm').click(); await visible(heading('Choose your secret code'));
  await enter(nextKeys); await button('Use this code').click(); await enter(nextKeys); await button('Confirm').click();
  await visible(heading('Ready for Lumen Bay'));
  const changed = await dbRead();
  assert.equal(changed.vault.address, initial.vault.address);
  assert.notEqual(changed.vault.salt, initial.vault.salt);
  assert.notEqual(changed.vault.iv, initial.vault.iv);
  await expire(); await page.reload(); await visible(heading('Welcome back'));
  await enter(keys); await button('Confirm').click(); await visible(page.getByRole('alert'));
  await enter(nextKeys); await button('Confirm').click(); await visible(heading('A place that’s yours'));
  console.log('PASS: expiry, wrong code, fresh reveal/change checks, hiding clears words, code rotation retains address.');
  await page.evaluate(() => new Promise(resolve => {
    const r = indexedDB.open('lumen-bay-identity', 1);
    r.onsuccess = () => { const db = r.result, tx = db.transaction('identity', 'readwrite'); tx.objectStore('identity').clear(); tx.oncomplete = () => { db.close(); resolve(); }; };
  }));
  await page.reload(); await visible(button('Restore with your 12 words'));
  assert.equal((await dbRead()).vault, null);
  await button('Restore with your 12 words').click();
  await page.getByLabel('Your recovery words', { exact: true }).fill(words.join(' '));
  await page.getByLabel('I have kept these 12 words safely on paper.').check();
  await button('Recover my Player ID').click(); await visible(heading('Choose your secret code'));
  await enter(keys); await button('Use this code').click(); await enter(keys); await button('Confirm').click(); await visible(heading('Ready for Lumen Bay'));
  assert.equal((await dbRead()).vault.address, initial.vault.address);
  const { restoreSecret } = await import('../src/identity/vault.ts');
  const testKey = restoreSecret(words.join(' ')).privateKey;
  assert.ok(requests.every(request => !request.toLowerCase().includes(testKey.toLowerCase()) && !request.includes(initial.vault.ciphertext)), 'private key and vault must not enter network requests');
  assert.ok(consoleMessages.every(message => !message.includes(words.join(' ')) && !message.toLowerCase().includes(testKey.toLowerCase())), 'secrets must not enter browser logs');
  assert.ok(requests.every(request => !request.includes(words.join(' ')) && !request.includes(encodeURIComponent(words.join(' ')))), 'phrase must not enter network requests');
  const persistent = await page.evaluate(() => JSON.stringify(localStorage));
  assert.ok(!persistent.includes(words.join(' ')) && !persistent.toLowerCase().includes(testKey.toLowerCase()), 'secrets must not enter localStorage');
  assert.deepEqual(errors, []);
  console.log('PASS: eviction offers restore without generation, local recovery preserves Player ID, no phrase/key/vault in network or logs; no plaintext secrets in localStorage, no page errors.');
  await context.close();
  // A browser storage error must not become a first-visit/new-wallet screen.
  const blocked = await browser.newContext({ viewport: { width: 390, height: 844 }, serviceWorkers: 'block' });
  await blocked.addInitScript(() => { Object.defineProperty(window, 'indexedDB', { value: undefined }); });
  const blockedPage = await blocked.newPage(); await blockedPage.goto(url);
  await blockedPage.getByRole('heading', { name: 'Your identity needs a moment' }).waitFor();
  assert.equal(await blockedPage.getByRole('button', { name: 'I’m new — create an identity' }).count(), 0);
  await blocked.close();
  console.log('PASS: unavailable storage is a recoverable error, never silent replacement.');
} finally { await browser.close(); }
