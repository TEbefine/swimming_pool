from glyphs import g

def expand(rows, k):
    rows = list(rows)
    for _ in range(k):
        n = len(rows); mid = (n - 1) / 2
        cands = [i for i in range(n - 1) if rows[i] == rows[i + 1]]
        i = min(cands, key=lambda i: abs(i + 0.5 - mid)) if cands else n // 2
        rows.insert(i, rows[i])
    return rows

def place(ch, rows, top):
    g("uni%04X" % ord(ch), ord(ch), top, "\n".join(rows))

def L(ch, rows, top=7, kind="cap"):
    rows = rows.split()
    h = len(rows)
    if kind == "low":
        zones = {"asc": [], "x": [], "desc": []}
        for i, r in enumerate(rows):
            y = top - i
            zones["asc" if y >= 6 else "x" if y >= 0 else "desc"].append(r)
        a = zones["asc"]
        if a and ch not in "ij":
            a = expand(a, 1)
        x = expand(zones["x"], 1)
        new = a + x + zones["desc"]
        ntop = 6 + len(a) if a else 6
        if ch in "ij": ntop = 8
        place(ch, new, ntop)
    elif h >= 7:
        extra = round(h * 1.25) - h
        bottom = top - h + 1
        new = expand(rows, extra)
        nb = bottom if bottom <= 0 else round(bottom * 1.25)
        place(ch, new, nb + len(new) - 1)
    else:
        place(ch, rows, round(top * 1.25) if top > 0 else top)

