# Nuan Pixel v3 — glyph source (structure follows real looped Thai letterforms)
# rows top->bottom, '#' = on. `top` = y of first row. Baseline y=0.
# Thai body = y0..y9 (10px). Upper marks from y11. Lower marks from y-2.
G = {}

def g(name, cp, top, rows, kind="base", **kw):
    rows = [r.strip() for r in rows.strip("\n").split("\n")]
    G[name] = dict(cp=cp, top=top, rows=rows, kind=kind, **kw)

def T(cp, rows, top=9, **kw):
    g("uni%04X" % cp, cp, top, rows, **kw)

